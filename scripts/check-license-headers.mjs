#!/usr/bin/env node
import { execSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import * as path from "node:path";

const repoRoot = process.cwd();
const shouldFix = process.argv.includes("--fix");
const copyright = "Copyright (c) 2026 Hannes Stauss <scalarion@nimblescape.com>";
const noticeLines = [
  "SPDX-License-Identifier: MIT",
  copyright,
  "Licensed under the MIT License. See LICENSE in the repository root for details.",
];

/**
 * Prose files are only stamped when this repo authored them. Everything else that happens
 * to be Markdown — README, generated docs, upstream notes — stays untouched.
 */
const DOC_PREFIXES = [".github/instructions/"];
const DOC_FILE_NAMES = new Set(["AGENTS.md", "CLAUDE.md", "spec/requirements.md"]);

/** Third-party sources that keep their own copyright. */
const VENDORED_PREFIXES = [".agents/skills/"];

/**
 * Generated by the shadcn CLI and then maintained here. MIT requires the upstream
 * copyright and permission notice to travel with the code, so these files carry shadcn's
 * notice next to ours — replacing it with ours alone would strip that attribution.
 * `dialog.tsx` and `tooltip.tsx` sit in the same directory but were written here.
 */
const UPSTREAM_COPYRIGHT = "Copyright (c) 2023 shadcn";
const SHADCN_DERIVED = new Set([
  "src/app/globals.css",
  "src/components/ui/button.tsx",
  "src/components/ui/card.tsx",
  "src/components/ui/input.tsx",
  "src/components/ui/label.tsx",
  "src/components/ui/select.tsx",
  "src/components/ui/textarea.tsx",
  "src/lib/utils.ts",
]);

function noticeFor(filePath) {
  if (!SHADCN_DERIVED.has(filePath)) {
    return noticeLines;
  }

  return [
    "SPDX-License-Identifier: MIT",
    UPSTREAM_COPYRIGHT,
    copyright,
    "",
    "Adapted from shadcn/ui (https://ui.shadcn.com), MIT licensed.",
    "See LICENSE and THIRD-PARTY-NOTICES.md in the repository root for details.",
  ];
}

/**
 * YAML frontmatter is only parsed when it starts at the very first byte, so anything put
 * above it silently disables it — and Prettier then reformats the block as prose, which
 * corrupts glob patterns inside it. Returns how much of the file the header must skip.
 */
function frontmatterLength(content) {
  if (!content.startsWith("---\n")) return 0;

  const end = content.indexOf("\n---\n", 3);
  return end === -1 ? 0 : end + "\n---\n".length;
}

function getTrackedFiles() {
  const output = execSync("git ls-files", {
    cwd: repoRoot,
    encoding: "utf8",
  });

  return output
    .split(/\r?\n/)
    .filter(Boolean)
    .filter((file) => {
      const lower = file.toLowerCase();

      if (
        lower.startsWith("node_modules/") ||
        lower.startsWith(".next/") ||
        lower.startsWith(".git/") ||
        lower.startsWith(".certs/") ||
        lower.startsWith(".vscode/") ||
        lower.startsWith("test-results/") ||
        lower.startsWith("public/.ds_store") ||
        lower.endsWith("/.ds_store") ||
        file === ".DS_Store"
      ) {
        return false;
      }

      // Vendored from upstream and copyrighted by their authors — stamping this repo's
      // notice onto them would misattribute someone else's work.
      if (VENDORED_PREFIXES.some((prefix) => lower.startsWith(prefix))) {
        return false;
      }

      return true;
    });
}

/**
 * Returns the comment syntax to stamp a file with, or null when the file is out of scope.
 * This is the single source of truth for which files need a header: anything without a
 * style — public assets, README, lockfiles, generated output — is never checked or fixed.
 */
function getStyle(filePath) {
  const ext = path.extname(filePath).toLowerCase();

  if (
    [
      ".ts",
      ".tsx",
      ".js",
      ".jsx",
      ".mjs",
      ".cjs",
      ".mts",
      ".cts",
      ".css",
      ".scss",
      ".less",
      ".rules",
    ].includes(ext)
  ) {
    return "block";
  }

  if ([".yml", ".yaml", ".sh", ".bash", ".zsh"].includes(ext)) {
    return "hash";
  }

  if ([".puml", ".plantuml"].includes(ext)) {
    return "plantuml";
  }

  if (
    ext === ".md" &&
    (DOC_PREFIXES.some((prefix) => filePath.startsWith(prefix)) || DOC_FILE_NAMES.has(filePath))
  ) {
    return "markdown";
  }

  return null;
}

function buildHeader(filePath, style) {
  const lines = noticeFor(filePath);
  const comment = (line, prefix) => (line ? `${prefix} ${line}` : prefix);

  switch (style) {
    case "block":
      return ["/*", ...lines.map((line) => comment(line, " *")), " */", ""].join("\n");
    case "markdown":
      return ["<!--", ...lines, "-->", ""].join("\n");
    case "hash":
      return [...lines.map((line) => comment(line, "#")), ""].join("\n");
    case "plantuml":
      return [...lines.map((line) => comment(line, "'")), ""].join("\n");
    default:
      return "";
  }
}

/**
 * Only a real top-of-file header counts. Scanning the whole file would also match the
 * example notice quoted inside the licensing docs, which would let genuinely unstamped
 * files pass the check.
 */
function hasHeader(filePath, fileContent) {
  const prefixLength = fileContent.startsWith("#!")
    ? fileContent.split(/\r?\n/, 1)[0].length + 1
    : frontmatterLength(fileContent);
  const head = fileContent.slice(prefixLength).split(/\r?\n/, 12).join("\n");

  return noticeFor(filePath)
    .filter(Boolean)
    .every((line) => head.includes(line));
}

/**
 * Drops a leading license comment so `--fix` can correct a wrong or outdated notice
 * instead of stacking a second one on top of it.
 */
function stripExistingHeader(body, style) {
  const blocks = {
    block: /^\/\*[\s\S]*?SPDX-License-Identifier[\s\S]*?\*\/\n+/,
    markdown: /^<!--[\s\S]*?SPDX-License-Identifier[\s\S]*?-->\n+/,
    hash: /^(?:#.*\n)*?#.*SPDX-License-Identifier.*\n(?:#.*\n)*\n*/,
    plantuml: /^(?:'.*\n)*?'.*SPDX-License-Identifier.*\n(?:'.*\n)*\n*/,
  };
  const pattern = blocks[style];

  return pattern ? body.replace(pattern, "") : body;
}

async function main() {
  const files = getTrackedFiles();
  const checkFiles = files.filter((file) => getStyle(file) !== null);
  const missing = [];

  for (const file of checkFiles) {
    const style = getStyle(file);
    if (!style) {
      continue;
    }

    const fullPath = path.join(repoRoot, file);
    const content = await readFile(fullPath, "utf8");

    if (hasHeader(file, content)) {
      continue;
    }

    missing.push(file);

    if (!shouldFix) {
      continue;
    }

    let shebang = "";
    if (content.startsWith("#!")) {
      const firstLine = content.split(/\r?\n/, 1)[0];
      shebang = `${firstLine}\n`;
    }

    // The notice goes below either of these, never above: both lose their meaning
    // the moment something precedes them.
    const prefixLength = shebang ? shebang.length : frontmatterLength(content);
    const prefix = content.slice(0, prefixLength);
    const remainder = stripExistingHeader(content.slice(prefixLength), style);
    const separator = prefixLength > 0 && !prefix.endsWith("\n\n") ? "\n" : "";
    const header = buildHeader(file, style);
    const next = `${prefix}${separator}${header}${remainder}`;
    await writeFile(fullPath, next, "utf8");
  }

  if (missing.length > 0 && !shouldFix) {
    console.error("Missing license headers in the following files:");
    for (const file of missing) {
      console.error(`- ${file}`);
    }
    process.exitCode = 1;
    return;
  }

  if (shouldFix) {
    console.log(`Added license headers to ${missing.length} file(s).`);
  } else {
    console.log(`Checked ${checkFiles.length} files. All include a valid MIT header.`);
  }
}

await main();
